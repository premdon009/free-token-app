"""plans.yml -> docs/paid/*.md

    uv run python scripts/gen_plans.py           # write the pages
    uv run python scripts/gen_plans.py --check   # exit 1 if the committed pages are out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from _plans import ROOT, STALE_DAYS, load
from _render import STATUS_BADGE, TRAINS_LABEL, esc, fmt_int, write_or_check, yesno

OUT = ROOT / "docs" / "paid"
HEADER = "<!-- GENERATED by scripts/gen_plans.py from plans.yml. Do not edit by hand. -->\n\n"

KIND_PAGE = {"subscription": "subscriptions.md", "payg": "pay-per-token.md", "harness": "harnesses.md"}
KIND_LABEL = {"subscription": "Subscription", "payg": "Pay per token", "harness": "Coding tool"}
API_LABEL = {
    "yes": "✅ yes",
    "limited": "🟠 own tools only",
    "no": "❌ no",
    "unknown": "⚪ not stated",
}
ENDPOINT_LABEL = {
    "openai": "OpenAI-compatible",
    "anthropic": "Anthropic-compatible",
    "both": "OpenAI- and Anthropic-compatible",
    "native": "own API only",
}


def usd(x: object) -> str:
    if x is None or x == "":
        return "—"
    x = float(x)
    if x == 0:
        return "free"
    s = f"{x:,.4f}".rstrip("0").rstrip(".")
    if "." in s and len(s.split(".")[1]) == 1:
        s += "0"
    return f"${s}"


def inr(x: object) -> str:
    if x is None or x == "":
        return "—"
    return "free" if float(x) == 0 else f"₹{float(x):,.0f}"


def newest(rows: list[dict]):
    return max(p["last_verified"] for p in rows)


def verified(p: dict, as_of) -> str:
    s = p["last_verified"].isoformat()
    return f"{s} ⏰ stale" if (as_of - p["last_verified"]).days > STALE_DAYS else s


def link(p: dict) -> str:
    return f"[{esc(p['name'])}]({KIND_PAGE[p['kind']]}#{p['id']})"


def price_span(p: dict) -> str:
    if p["kind"] == "payg":
        outs = [m["output"] for m in p["models"]]
        return f"{usd(min(outs))}–{usd(max(outs))} / 1M out" if len(set(outs)) > 1 else f"{usd(outs[0])} / 1M out"
    paid = [t["usd_month"] for t in p["tiers"] if t.get("usd_month") is not None]
    if not paid:
        return "see tiers"
    lo, hi = min(paid), max(paid)
    return f"{usd(lo)}/mo" if lo == hi else f"{usd(lo)}–{usd(hi)}/mo"


def facts_table(p: dict, as_of) -> str:
    rows_ = [("Vendor", p["vendor"]), ("Type", KIND_LABEL[p["kind"]])]
    if p["kind"] == "payg":
        rows_.append(("API", ENDPOINT_LABEL[p["endpoint"]] + (f" · `{p['base_url']}`" if p.get("base_url") else "")))
        if p.get("fees"):
            rows_.append(("Fees and credits", p["fees"]))
    else:
        rows_.append(("Use through a router / as an API key", API_LABEL[p["api_access"]]))
        if p.get("byok"):
            rows_.append(("Bring your own key (BYOK)", p["byok"]))
    rows_.append(("Trains on prompts", TRAINS_LABEL[p["trains_on_prompts"]]
                  + (f" ([terms]({p['terms_source']}))" if p.get("terms_source") else "")))
    if p.get("region_notes"):
        rows_.append(("Region", p["region_notes"]))
    rows_.append(("Pricing source", f"[{p['pricing_source']}]({p['pricing_source']})"))
    rows_.append(("Verified", verified(p, as_of)))
    out = ["| | |\n|---|---|\n"]
    out += [f"| {k} | {esc(v)} |\n" for k, v in rows_]
    return "".join(out)


def tier_table(p: dict) -> str:
    out = ["| Tier | USD / month | INR / month | Models | Limits | Works in |\n", "|---|---|---|---|---|---|\n"]
    for t in p["tiers"]:
        out.append(
            f"| {esc(t['name'])} | {usd(t.get('usd_month'))} | {inr(t.get('inr_month'))} | "
            f"{esc(t.get('models', ''))} | {esc(t['limits'])} | {esc(', '.join(t.get('tools') or []))} |\n"
        )
    return "".join(out)


def page_tiered(rows: list[dict], kind: str, title: str, intro: str) -> str:
    as_of = newest(rows)
    out = [HEADER, f"# {title}\n\n{intro}\n\n"]
    for p in sorted((r for r in rows if r["kind"] == kind), key=lambda r: r["name"].lower()):
        out.append(f"## {esc(p['name'])}{STATUS_BADGE[p['status']]} {{#{p['id']}}}\n\n")
        out.append(facts_table(p, as_of) + "\n" + tier_table(p))
        if p.get("notes"):
            out.append(f"\n{esc(p['notes'])}\n")
        out.append("\n")
    return "".join(out)


def model_pairs(rows: list[dict], role: str) -> list[tuple[dict, dict]]:
    pairs = [(p, m) for p in rows if p["kind"] == "payg" and p["status"] != "retired"
             for m in p["models"] if m["role"] == role]
    return sorted(pairs, key=lambda pm: (pm[1]["output"], pm[1]["input"], pm[0]["name"].lower()))


def model_table(pairs: list[tuple[dict, dict]]) -> str:
    out = ["| Model | Provider | Input | Cached input | Output | Context | Tools | Trains on prompts |\n",
           "|---|---|---|---|---|---|---|---|\n"]
    for p, m in pairs:
        out.append(
            f"| `{esc(m['id'])}` | {link(p)} | {usd(m['input'])} | {usd(m.get('cached_input'))} | "
            f"{usd(m['output'])} | {fmt_int(m.get('context'))} | {yesno(m['tools']) if 'tools' in m else '—'} | "
            f"{TRAINS_LABEL[p['trains_on_prompts']]} |\n"
        )
    if not pairs:
        out.append("| — | | | | | | | |\n")
    return "".join(out)


def page_payg(rows: list[dict]) -> str:
    as_of = newest(rows)
    out = [HEADER, "# Pay per token\n\n",
           "Prices are US dollars per **1 million tokens**, from each provider's own pricing page. "
           "Cached input is the price for a repeated prompt prefix, where the provider offers it. "
           "Rows are sorted by output price, cheapest first. Providers change prices often: check the "
           "source link before you rely on a number.\n\n",
           "## Orchestrator models\n\nStrong models for planning, hard reasoning and reviewing other "
           "models' work. See [orchestration](../agents/orchestration.md).\n\n",
           model_table(model_pairs(rows, "orchestrator")),
           "\n## Worker models\n\nCheap models that are good enough at coding and tool calling to do "
           "bounded tasks a stronger model hands them.\n\n",
           model_table(model_pairs(rows, "worker")),
           "\n## Providers\n\n"]
    for p in sorted((r for r in rows if r["kind"] == "payg"), key=lambda r: r["name"].lower()):
        out.append(f"### {esc(p['name'])}{STATUS_BADGE[p['status']]} {{#{p['id']}}}\n\n")
        out.append(facts_table(p, as_of))
        if p.get("notes"):
            out.append(f"\n{esc(p['notes'])}\n")
        out.append("\n")
    return "".join(out)


def page_index(rows: list[dict]) -> str:
    as_of = newest(rows)
    out = [HEADER, "# Paid plans\n\n",
           "Free tiers run out, and free models are weaker at agentic coding. This section covers what you "
           "can pay for instead: **subscriptions** (a flat monthly price for a vendor's own apps and coding "
           "tools), **coding-tool plans** (opencode, Cline, Command Code and others), **pay-per-token APIs** (usable from any agent, from your own apps and through the "
           "[router](../router/index.md)), and the **free quotas of coding tools** that log in with an "
           "account instead of an API key.\n\n",
           f"{len(rows)} entries, newest check **{as_of.isoformat()}**. A row more than {STALE_DAYS} days "
           "older than the newest check is marked ⏰ stale.\n\n",
           "!!! warning \"Subscriptions are not API keys\"\n"
           "    Most subscriptions only work inside the vendor's own apps and CLIs. Using a subscription login "
           "through a router or a third-party tool is often against its terms. The **Router / API** column "
           "says what each plan's own terms allow.\n\n",
           "| Plan | Type | Price | Router / API | Trains on prompts | Source | Verified |\n",
           "|---|---|---|---|---|---|---|\n"]
    order = {"subscription": 0, "harness": 1, "payg": 2}
    for p in sorted(rows, key=lambda r: (order[r["kind"]], r["name"].lower())):
        api = "✅ yes" if p["kind"] == "payg" else API_LABEL[p["api_access"]]
        out.append(
            f"| {link(p)}{STATUS_BADGE[p['status']]} | {KIND_LABEL[p['kind']]} | {esc(price_span(p))} | {api} | "
            f"{TRAINS_LABEL[p['trains_on_prompts']]} | [link]({p['pricing_source']}) | {verified(p, as_of)} |\n"
        )
    out.append("\nDetails: [subscriptions](subscriptions.md) · [pay per token](pay-per-token.md) · "
               "[coding tools](harnesses.md) · how to combine them: "
               "[orchestration](../agents/orchestration.md)\n")
    return "".join(out)


def render(rows: list[dict]) -> dict[Path, str]:
    return {
        OUT / "index.md": page_index(rows),
        OUT / "subscriptions.md": page_tiered(
            rows, "subscription", "Subscriptions",
            "Flat monthly plans. Limits are quoted from each plan page; most reset on a rolling window "
            "(for example every 5 hours) as well as weekly or monthly."),
        OUT / "pay-per-token.md": page_payg(rows),
        OUT / "harnesses.md": page_tiered(
            rows, "harness", "Coding tools",
            "Coding agents and IDEs that sell their own plan or come with a free quota tied to an account "
            "(opencode, Cline, Command Code, Antigravity CLI and others). **BYOK** says whether you can bring your own "
            "API key instead, which is how you point a tool at the [router](../router/index.md) or a "
            "pay-per-token provider. Account quotas don't go through the router; they're a backup when the "
            "router's free quotas run out."),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated pages are out of date")
    args = ap.parse_args()
    return write_or_check(render(load()), ROOT, args.check, "paid pages", "uv run python scripts/gen_plans.py")


if __name__ == "__main__":
    sys.exit(main())
