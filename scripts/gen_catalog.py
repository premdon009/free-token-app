"""providers.yml -> docs/catalog/*.md

    uv run python scripts/gen_catalog.py           # write the pages
    uv run python scripts/gen_catalog.py --check   # exit 1 if the committed pages are out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from _providers import ROOT, STALE_DAYS, load, model_lanes

OUT = ROOT / "docs" / "catalog"
HEADER = "<!-- GENERATED by scripts/gen_catalog.py from providers.yml. Do not edit by hand. -->\n\n"

FREE_TYPE_LABEL = {
    "permanent": "Permanent free tier",
    "renewable-credit": "Renewing credit",
    "trial": "Trial credit (one-time)",
    "keyless": "Keyless (no sign-up)",
    "local": "Local (your machine)",
}
STATUS_BADGE = {"active": "", "unclear": " ⚠️ unclear", "retired": " ❌ retired"}
TRAINS_LABEL = {"yes": "🔴 yes", "no": "🟢 no", "opt-out": "🟠 opt-out", "unknown": "⚪ unknown"}


def esc(text: object) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def yesno(v: object) -> str:
    return "yes" if v else "no"


def fmt_int(n: object) -> str:
    if n is None or n == "":
        return "—"
    n = int(n)
    if n >= 1_000_000 and n % 1_000_000 == 0:
        return f"{n // 1_000_000}M"
    if n >= 1_000_000:
        return f"{n / 1_048_576:.0f}M" if n % 1_048_576 == 0 else f"{n:,}"
    if n >= 1000 and n % 1000 == 0:
        return f"{n // 1000}K"
    if n >= 1000 and n % 1024 == 0:
        return f"{n // 1024}K"
    if n >= 1000:
        return f"{n / 1000:.1f}K"
    return str(n)


def short_limits(p: dict) -> str:
    lim = p.get("limits") or {}
    parts = [f"{fmt_int(lim[k])} {k.upper()}" for k in ("rpm", "rpd", "tpm", "tpd") if lim.get(k)]
    return ", ".join(parts) if parts else "see notes"


def newest(rows: list[dict]):
    return max(p["last_verified"] for p in rows)


def stale(p: dict, as_of) -> bool:
    return (as_of - p["last_verified"]).days > STALE_DAYS


def verified(p: dict, as_of) -> str:
    s = p["last_verified"].isoformat()
    return f"{s} ⏰ stale" if stale(p, as_of) else s


def link(p: dict) -> str:
    return f"[{esc(p['name'])}](providers.md#{p['id']})"


def page_index(rows: list[dict]) -> str:
    as_of = newest(rows)
    out = [HEADER, "# Catalog\n\n"]
    out.append(
        f"{len(rows)} services, newest check **{as_of.isoformat()}**. A row older than {STALE_DAYS} days "
        "than the newest check is marked ⏰ stale. Limits change often: the **Source** link is the "
        "provider's own page, so check it before you rely on a number.\n\n"
    )
    out.append("Trains on prompts: 🟢 no · 🟠 opt-out (turn it off in settings) · 🔴 yes · ⚪ unknown.\n\n")
    out.append("| Service | Free type | Card | Limits | Trains on prompts | Commercial use | In router | Source | Verified |\n")
    out.append("|---|---|---|---|---|---|---|---|---|\n")
    order = {"active": 0, "unclear": 1, "retired": 2}
    for p in sorted(rows, key=lambda r: (order[r["status"]], r["kind"] == "local", r["name"].lower())):
        out.append(
            f"| {link(p)}{STATUS_BADGE[p['status']]} | {FREE_TYPE_LABEL[p['free_type']]} | "
            f"{yesno(p['card_required'])} | {esc(short_limits(p))} | {TRAINS_LABEL[p['trains_on_prompts']]} | "
            f"{p['commercial_use']} | {'✅' if p['router'].get('include') else '—'} | "
            f"[link]({p['limits_source']}) | {verified(p, as_of)} |\n"
        )
    out.append("\nBy use: [coding](coding.md) · [chat](chat.md) · [vision](vision.md) · "
               "[embeddings](embeddings.md) · [private](private.md) · [by free type](by-free-type.md)\n")
    return "".join(out)


def page_providers(rows: list[dict]) -> str:
    as_of = newest(rows)
    out = [HEADER, "# Provider details\n\n"]
    for p in sorted(rows, key=lambda r: (r["kind"] == "local", r["name"].lower())):
        r = p["router"]
        out.append(f"## {esc(p['name'])} {{#{p['id']}}}\n\n")
        if p["status"] != "active":
            out.append(f"!!! warning \"Status: {p['status']}\"\n    {esc(p['limits'].get('text', ''))}\n\n")
        out.append("| | |\n|---|---|\n")
        rows_ = [
            ("Free type", FREE_TYPE_LABEL[p["free_type"]]),
            ("Kind", p["kind"]),
            ("Card / phone needed", f"{yesno(p['card_required'])} / {yesno(p.get('phone_required'))}"),
            ("Limits", f"{short_limits(p)}. {p['limits'].get('text', '')}"),
            ("Limits source", f"[{p['limits_source']}]({p['limits_source']})"),
            ("Trains on prompts", TRAINS_LABEL[p["trains_on_prompts"]]
             + (f" ([policy]({p['trains_source']}))" if p.get("trains_source") else "")),
            ("Commercial use", p["commercial_use"]),
            ("API", f"{p['api']}-compatible · `{p['base_url']}`"),
            ("Get a key", f"[{p['signup_url']}]({p['signup_url']})"),
            ("Docs", f"[{p['docs_url']}]({p['docs_url']})"),
            ("Router", f"lanes: {', '.join(r.get('lanes') or []) or '—'}" if r.get("include") else "not in the default chain"),
            ("Region", p.get("region_notes") or "—"),
            ("Verified", verified(p, as_of)),
        ]
        for k, v in rows_:
            out.append(f"| {k} | {esc(v)} |\n")
        if p["models"]:
            out.append("\n| Model id | Context | Tools | Vision | Router lanes |\n|---|---|---|---|---|\n")
            for m in p["models"]:
                lanes = ", ".join(model_lanes(p, m)) if r.get("include") else "—"
                kind = " (embeddings)" if m.get("embedding") else ""
                out.append(
                    f"| `{esc(m['id'])}`{kind} | {fmt_int(m.get('context'))} | {yesno(m.get('tools'))} | "
                    f"{yesno(m.get('vision'))} | {lanes or '—'} |\n"
                )
        if p.get("notes"):
            out.append(f"\n{esc(p['notes'])}\n")
        out.append("\n")
    return "".join(out)


def model_rows(rows: list[dict], pred) -> list[tuple[dict, dict]]:
    out = []
    for p in rows:
        if p["status"] == "retired":
            continue
        for m in p["models"]:
            if pred(p, m):
                out.append((p, m))
    return sorted(out, key=lambda pm: (pm[0]["kind"] == "local", -(pm[1].get("context") or 0), pm[0]["name"].lower()))


def model_table(pairs: list[tuple[dict, dict]]) -> str:
    out = ["| Model id | Service | Context | Tools | Vision | Trains on prompts | Limits |\n",
           "|---|---|---|---|---|---|---|\n"]
    for p, m in pairs:
        out.append(
            f"| `{esc(m['id'])}` | {link(p)} | {fmt_int(m.get('context'))} | {yesno(m.get('tools'))} | "
            f"{yesno(m.get('vision'))} | {TRAINS_LABEL[p['trains_on_prompts']]} | {esc(short_limits(p))} |\n"
        )
    if not pairs:
        out.append("| — | | | | | | |\n")
    return "".join(out)


USE_PAGES = {
    "coding.md": (
        "Coding agents",
        "Models with tool calling and at least 64K context, which agents such as Claude Code, Cline and aider "
        "need. Free models are clearly weaker than Claude at multi-step agentic coding: expect more retries, "
        "and keep tasks small.",
        lambda p, m: not m.get("embedding") and m.get("tools") and (m.get("context") or 0) >= 64_000,
    ),
    "chat.md": (
        "Chat and app calls",
        "Every free chat model. For apps, prefer a service whose commercial-use column says yes.",
        lambda p, m: not m.get("embedding"),
    ),
    "vision.md": (
        "Vision (image input)",
        "Models that accept images.",
        lambda p, m: m.get("vision"),
    ),
    "embeddings.md": (
        "Embeddings (RAG and search)",
        "Embedding models. Keep one model per index: vectors from different models don't mix.",
        lambda p, m: m.get("embedding"),
    ),
    "private.md": (
        "Private use",
        "Only services that say they don't train on your prompts, plus local models. Even here, never send "
        "passwords, keys or client data you aren't allowed to share with a third party.",
        lambda p, m: p["trains_on_prompts"] == "no" and not m.get("embedding"),
    ),
}


def page_use(title: str, intro: str, pairs) -> str:
    return f"{HEADER}# {title}\n\n{intro}\n\n{model_table(pairs)}\nSee the [full catalog](index.md) for limits and sources.\n"


def page_by_type(rows: list[dict]) -> str:
    out = [HEADER, "# By free type\n\n"]
    for ft, label in FREE_TYPE_LABEL.items():
        group = [p for p in rows if p["free_type"] == ft]
        if not group:
            continue
        out.append(f"## {label}\n\n")
        for p in sorted(group, key=lambda r: r["name"].lower()):
            out.append(f"- {link(p)}{STATUS_BADGE[p['status']]}: {esc(short_limits(p))}. {esc(p['limits'].get('text', ''))}\n")
        out.append("\n")
    return "".join(out)


def render(rows: list[dict]) -> dict[Path, str]:
    pages = {
        OUT / "index.md": page_index(rows),
        OUT / "providers.md": page_providers(rows),
        OUT / "by-free-type.md": page_by_type(rows),
    }
    for name, (title, intro, pred) in USE_PAGES.items():
        pages[OUT / name] = page_use(title, intro, model_rows(rows, pred))
    return pages


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated pages are out of date")
    args = ap.parse_args()
    pages = render(load())
    if args.check:
        stale_files = [p for p, text in pages.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale_files:
            print(f"out of date: {p.relative_to(ROOT)}")
        if stale_files:
            print("run: uv run python scripts/gen_catalog.py")
            return 1
        print(f"catalog up to date ({len(pages)} pages)")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for p, text in pages.items():
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(pages)} pages to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
