def render(rows: list[dict]) -> dict[Path, str]:
    out = {
        ROUTER / "litellm.yaml": render_litellm(rows),
        ROUTER / ".env.example": render_env_example(rows),
        DOCS / "lanes.md": render_lanes_doc(rows),
    }
    for name, text in render_configs(rows).items():
        out[CONFIGS / name] = text
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = ap.parse_args()
    files = render(load())
    if args.check:
        bad = [p for p, text in files.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in bad:
            print(f"out of date: {p.relative_to(ROOT)}")
        if bad:
            print("run: uv run python scripts/gen_router.py")
            return 1
        print(f"router files up to date ({len(files)} files)")
        return 0
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
