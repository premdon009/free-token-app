"""providers.yml -> router/litellm.yaml, router/.env.example, configs/*, docs/router/lanes.md

    uv run python scripts/gen_router.py           # write the files
    uv run python scripts/gen_router.py --check   # exit 1 if the committed files are out of date

Each lane (free/coding, free/fast, free/private, free/embed, local) is a LiteLLM model name whose
first deployment is the best provider; the rest of the chain is its fallback list, tried in order.
A deployment that fails (429, 5xx, missing key) goes on cooldown so later calls skip it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

from _providers import LANES, ROOT, load, model_lanes

ROUTER = ROOT / "router"
CONFIGS = ROOT / "configs"
DOCS = ROOT / "docs" / "router"
PORT = 4000
BASE = f"http://127.0.0.1:{PORT}"
DEFAULT_MAX_PER_LANE = 2
GEN = "GENERATED by scripts/gen_router.py from providers.yml. Do not edit by hand."

LANE_NAME = {"coding": "free/coding", "fast": "free/fast", "private": "free/private", "embed": "free/embed", "local": "local"}
LANE_FOR = {
    "coding": "Claude Code, Cline, aider, opencode, Codex",
    "fast": "Chat and small app calls",
    "private": "Anything sensitive: only services that don't train on prompts, then local",
    "embed": "RAG and search embeddings",
    "local": "Offline, or when every free quota is used up",
}


def deployment(p: dict, m: dict) -> dict:
    r = p["router"]
    params: dict = {"model": m.get("litellm_model") or f"openai/{m['id']}"}
    if r.get("base_url_env"):
        params["api_base"] = f"os.environ/{r['base_url_env']}"
    else:
        params["api_base"] = p["base_url"]
    if r.get("key_env"):
        params["api_key"] = f"os.environ/{r['key_env']}"
    return params


def chains(rows: list[dict]) -> dict[str, list[tuple[dict, dict]]]:
    routed = [p for p in rows if p["router"].get("include")]
    routed.sort(key=lambda p: (p["router"].get("priority", 50), rows.index(p)))
    out: dict[str, list[tuple[dict, dict]]] = {lane: [] for lane in LANES}
    for p in routed:
        cap = p["router"].get("max_per_lane", DEFAULT_MAX_PER_LANE)
        for lane in LANES:
            picked = [m for m in p["models"] if lane in model_lanes(p, m)][:cap]
            out[lane].extend((p, m) for m in picked)
    return out


def dep_name(p: dict, m: dict) -> str:
    return f"{p['id']}/{m['id']}"


def render_litellm(rows: list[dict]) -> str:
    lane_chains = chains(rows)
    model_list = []
    seen = set()
    for lane in LANES:
        for p, m in lane_chains[lane]:
            name = dep_name(p, m)
            if name in seen:
                continue
            seen.add(name)
            model_list.append({
                "model_name": name,
                "litellm_params": deployment(p, m),
                "model_info": {"mode": "embedding" if m.get("embedding") else "chat"},
            })
    fallbacks = []
    for lane in LANES:
        chain = lane_chains[lane]
        if not chain:
            continue
        first_p, first_m = chain[0]
        model_list.append({
            "model_name": LANE_NAME[lane],
            "litellm_params": deployment(first_p, first_m),
            "model_info": {"mode": "embedding" if lane == "embed" else "chat"},
        })
        rest = [dep_name(p, m) for p, m in chain[1:]]
        if rest:
            fallbacks.append({LANE_NAME[lane]: rest})
    config = {
        "model_list": model_list,
        "litellm_settings": {
            "drop_params": True,
            "num_retries": 0,
            "request_timeout": 120,
            "fallbacks": fallbacks,
            "telemetry": False,
        },
        "router_settings": {
            "allowed_fails": 1,
            "cooldown_time": 120,
        },
        "general_settings": {
            "master_key": "os.environ/LITELLM_MASTER_KEY",
        },
    }
    head = f"# {GEN}\n# Lanes: {', '.join(LANE_NAME[l] for l in LANES)}. Keys come from router/.env.\n"
    return head + yaml.safe_dump(config, sort_keys=False, default_flow_style=False, width=120)


def render_env_example(rows: list[dict]) -> str:
    out = [
        f"# {GEN}\n",
        "# Copy to router/.env, fill in what you have, then: chmod 600 router/.env\n",
        "# One account per provider, used within its terms. An empty key just skips that provider.\n",
        "# Never commit router/.env.\n\n",
        "# Any long random string; clients (Claude Code, apps) send it as their API key.\n",
        "# Make one with: python3 -c \"import secrets; print('sk-' + secrets.token_urlsafe(32))\"\n",
        "LITELLM_MASTER_KEY=\n\n",
    ]
    for p in rows:
        r = p["router"]
        envs = [e for e in (r.get("key_env"), r.get("base_url_env")) if e]
        if not envs:
            continue
        state = "in router" if r.get("include") else "not in the default chain"
        out.append(f"# {p['name']} ({state}) · key: {p['signup_url']}\n")
        for e in envs:
            if e == r.get("base_url_env") and p["kind"] == "local":
                out.append(f"{e}=http://127.0.0.1:11434\n")
            elif e == r.get("base_url_env"):
                out.append(f"{e}={p['base_url'].replace('{account_id}', '<account_id>')}\n")
            else:
                out.append(f"{e}=\n")
        out.append("\n")
    return "".join(out)


def render_lanes_doc(rows: list[dict]) -> str:
    lane_chains = chains(rows)
    out = [f"<!-- {GEN} -->\n\n# Lanes\n\n",
           "Ask the router for a **lane name** instead of a model. It tries the first entry, and on a 429, "
           "a 5xx or a missing key moves to the next one. A failing entry is skipped for 120 seconds.\n\n"]
    for lane in LANES:
        chain = lane_chains[lane]
        out.append(f"## `{LANE_NAME[lane]}`\n\n{LANE_FOR[lane]}.\n\n")
        if not chain:
            out.append("_No providers in this lane._\n\n")
            continue
        out.append("| # | Service | Model | Key in `router/.env` |\n|---|---|---|---|\n")
        for i, (p, m) in enumerate(chain, 1):
            key = p["router"].get("key_env") or p["router"].get("base_url_env") or "—"
            out.append(f"| {i} | [{p['name']}](../catalog/providers.md#{p['id']}) | `{m['id']}` | `{key}` |\n")
        out.append("\n")
    out.append("To change a chain, edit `router` and `models` in `providers.yml` and run "
               "`uv run python scripts/gen_router.py`.\n")
    return "".join(out)


def min_context(chain: list[tuple[dict, dict]]) -> int:
    ctx = [m.get("context") for _, m in chain if m.get("context")]
    return min(ctx) if ctx else 32768


